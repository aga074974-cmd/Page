        "هست", "باش",
        "گیر", "بر", "آور", "خور", "زن", "کش", "رس", "افت", "خیز", "مان", "نویس",
        "خوان", "پرس", "فروش", "خر", "ساز", "یاب", "شناس", "فهم", "بخش", "گذار",
        "گرد", "ایست", "نشین", "پوش", "بند", "شکن", "سوز", "ریز", "پرد", "جه",
        "خند", "گری", "ترس", "دو", "پر", "کاه", "افزا", "رسان", "نما", "بخوان",
        "شمار", "سنج", "طلب", "کوش", "ورز", "پذیر", "گنج", "چین", "کار", "دزد",
        "بوس", "خواب", "پز", "شور", "تراش", "بافت", "باف", "دوز", "کوب", "مال",
        "لرز", "جنب", "چرخ", "رقص", "پرست", "ستان", "سپار", "فرست", "گسل", "نگر",
        "بلع", "جو", "خیزان", "رنج", "زای", "شکاف", "طپ", "غلت", "کاو", "گداز",
        "گمار", "لغز", "نال", "وز", "هراس", "یازد", "آموز", "آزما", "آسا", "آشام",
        "آغاز", "آلای", "انداز", "انگیز", "اندوز", "برد", "پیوند", "تاب", "تپ",
        "توانست", "جوی", "چسب", "خراش", "دم", "دوش", "رهان", "زیب", "سا", "شتاب",
    )

    /**
     * ریشهٔ ماضی. این‌ها **می‌توانند بی‌شناسه بیایند** («می‌رفت» درست است)، و چون
     * همه به ت/د ختم می‌شوند با اسم‌های رایج اشتباه نمی‌شوند.
     */
    val PAST: Set<String> = setOf(
        "کرد", "شد", "رفت", "گفت", "دید", "بود", "آمد", "داد", "خواست", "توانست",
        "دانست", "گرفت", "زد", "برد", "آورد", "خورد", "نشست", "گذاشت", "افتاد",
