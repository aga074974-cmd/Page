package ir.page.persianocr.text

/**
 * ریشه‌های فعلیِ پرکاربردِ فارسی — تنها چیزی که [PersianSpellCorrector] برای
 * درجِ نیم‌فاصلهٔ «می»/«نمی» به آن نیاز دارد.
 *
 * ── چرا فهرستِ دستی و نه واژه‌نامه ────────────────────────────────────────────
 * قاعدهٔ ساده‌ی «اگر بعد از می یک واژهٔ معتبر بود، نیم‌فاصله بگذار» غلط است:
 * «میدان» را به «می‌دان» و «میلاد» را به «می‌لاد» تبدیل می‌کرد، چون «دان» و «لاد»
 * هر دو در واژه‌نامه هستند. با فهرستِ ریشه‌های فعلی، نیم‌فاصله فقط وقتی درج می‌شود
 * که چیزی که بعد از «می» می‌آید واقعاً صرفِ یک فعل باشد.
 */
internal object PersianVerbStems {

    /**
     * ریشهٔ مضارع. برای این‌ها **شناسه الزامی است** («می‌دان» فعل نیست، «می‌دانم» هست)
     * و همین قید است که «میدان» را نجات می‌دهد.
     */
